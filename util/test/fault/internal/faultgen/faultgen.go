// Package faultgen generates the fault decorators in util/test/fault from the interfaces they
// wrap. Each generated decorator delegates every method explicitly (it never embeds the
// interface), so adding a method to a wrapped interface breaks the build until the decorators
// are regenerated with `go generate ./util/test/fault`.
package faultgen

import (
	"bytes"
	"fmt"
	"go/format"
	"go/types"
	"path"
	"sort"
	"strings"

	"github.com/bsv-blockchain/teranode/errors"
	"golang.org/x/tools/go/packages"
)

// Target is one interface to decorate.
type Target struct {
	PkgPath  string // import path of the package declaring the interface
	Iface    string // interface name
	Type     string // generated decorator type
	StoreKey string // fault.Store* constant naming it
	File     string // output file name
}

// Targets are the interfaces util/test/fault decorates.
var Targets = []Target{
	{"github.com/bsv-blockchain/teranode/stores/utxo", "Store", "UTXOStore", "StoreUTXO", "zz_utxo_store.go"},
	{"github.com/bsv-blockchain/teranode/stores/blob", "Store", "BlobStore", "StoreBlob", "zz_blob_store.go"},
	{"github.com/bsv-blockchain/teranode/services/blockchain", "ClientI", "BlockchainClient", "StoreBlockchain", "zz_blockchain_client.go"},
	{"github.com/bsv-blockchain/teranode/stores/blockchain", "Store", "BlockchainStore", "StoreBlockchainStore", "zz_blockchain_store.go"},
}

// MethodsFile is the generated registry of method names per decorated interface.
const MethodsFile = "zz_methods.go"

const header = "// Code generated by util/test/fault/internal/faultgen; DO NOT EDIT.\n\n"

// Generate renders every decorator and the method registry, keyed by file name. dir is any
// directory inside the module (it locates go.mod).
func Generate(dir string) (map[string][]byte, error) {
	paths := make([]string, 0, len(Targets))
	for _, t := range Targets {
		paths = append(paths, t.PkgPath)
	}

	pkgs, err := packages.Load(&packages.Config{Mode: packages.NeedName | packages.NeedTypes, Dir: dir}, paths...)
	if err != nil {
		return nil, err
	}

	byPath := map[string]*packages.Package{}

	for _, p := range pkgs {
		if len(p.Errors) > 0 {
			return nil, errors.NewProcessingError("loading %s: %v", p.PkgPath, p.Errors[0])
		}

		byPath[p.PkgPath] = p
	}

	out := map[string][]byte{}
	registry := map[string]map[string]bool{} // method -> store key -> returns error

	for _, t := range Targets {
		p, ok := byPath[t.PkgPath]
		if !ok {
			return nil, errors.NewProcessingError("package %s not loaded", t.PkgPath)
		}

		obj := p.Types.Scope().Lookup(t.Iface)
		if obj == nil {
			return nil, errors.NewProcessingError("%s.%s not found", t.PkgPath, t.Iface)
		}

		iface, ok := obj.Type().Underlying().(*types.Interface)
		if !ok {
			return nil, errors.NewProcessingError("%s.%s is not an interface", t.PkgPath, t.Iface)
		}

		src, err := render(t, obj.Type(), iface, registry)
		if err != nil {
			return nil, errors.NewProcessingError("rendering %s.%s", t.PkgPath, t.Iface, err)
		}

		out[t.File] = src
	}

	reg, err := renderRegistry(registry)
	if err != nil {
		return nil, err
	}

	out[MethodsFile] = reg

	return out, nil
}

// importer renders type names with placeholder qualifiers, then assigns each imported
// package an alias that is unique in the file.
type importer struct {
	names map[string]string // path -> package name
}

func (im *importer) qualifier(p *types.Package) string {
	im.names[p.Path()] = p.Name()
	return "\x00" + p.Path() + "\x00"
}

func (im *importer) typeString(t types.Type) string {
	return types.TypeString(t, im.qualifier)
}

// aliases picks a unique alias per path: the package name, or the parent directory joined to
// the name when two paths share a name.
func (im *importer) aliases() map[string]string {
	paths := make([]string, 0, len(im.names))
	for p := range im.names {
		paths = append(paths, p)
	}

	sort.Strings(paths)

	count := map[string]int{}
	for _, p := range paths {
		count[im.names[p]]++
	}

	out := map[string]string{}

	for _, p := range paths {
		name := im.names[p]
		if count[name] > 1 {
			name = strings.ReplaceAll(path.Base(path.Dir(p)), "-", "") + name
		}

		out[p] = name
	}

	return out
}

func (im *importer) resolve(src string) (string, []string) {
	al := im.aliases()

	var imports []string

	for p, a := range al {
		src = strings.ReplaceAll(src, "\x00"+p+"\x00", a)

		if a == im.names[p] && path.Base(p) == a {
			imports = append(imports, fmt.Sprintf("%q", p))
		} else {
			imports = append(imports, fmt.Sprintf("%s %q", a, p))
		}
	}

	sort.Strings(imports)

	return src, imports
}

func render(t Target, named types.Type, iface *types.Interface, registry map[string]map[string]bool) ([]byte, error) {
	im := &importer{names: map[string]string{}}
	ifaceName := im.typeString(named)

	var body bytes.Buffer

	fmt.Fprintf(&body, "// %s decorates %s with the rules of a Plan. Every method is delegated explicitly, so a\n", t.Type, ifaceName)
	fmt.Fprintf(&body, "// method added to the interface fails to compile here until the decorators are regenerated.\n")
	fmt.Fprintf(&body, "type %s struct {\n\tinner %s\n\tplan  *Plan\n}\n\n", t.Type, ifaceName)
	fmt.Fprintf(&body, "var _ %s = (*%s)(nil)\n\n", ifaceName, t.Type)
	fmt.Fprintf(&body, "// New%s wraps inner so that every call is logged on plan and subject to its rules.\n", t.Type)
	fmt.Fprintf(&body, "func New%s(inner %s, plan *Plan) *%s {\n\treturn &%s{inner: inner, plan: plan}\n}\n\n", t.Type, ifaceName, t.Type, t.Type)

	for i := 0; i < iface.NumMethods(); i++ {
		m := iface.Method(i)
		if !m.Exported() {
			return nil, errors.NewProcessingError("unexported method %s cannot be decorated", m.Name())
		}

		sig := m.Type().(*types.Signature)
		if sig.TypeParams().Len() > 0 {
			return nil, errors.NewProcessingError("generic method %s cannot be decorated", m.Name())
		}

		hasErr := renderMethod(&body, im, t, m.Name(), sig)

		if registry[m.Name()] == nil {
			registry[m.Name()] = map[string]bool{}
		}

		registry[m.Name()][t.StoreKey] = hasErr
	}

	src, imports := im.resolve(body.String())

	var file bytes.Buffer

	file.WriteString(header)
	file.WriteString("package fault\n\n")

	if len(imports) > 0 {
		var std, other []string

		for _, imp := range imports {
			// A standard-library path has no dot in its first element.
			p := strings.Trim(imp[strings.Index(imp, `"`):], `"`)
			if !strings.Contains(strings.SplitN(p, "/", 2)[0], ".") {
				std = append(std, imp)
			} else {
				other = append(other, imp)
			}
		}

		file.WriteString("import (\n")

		for _, imp := range std {
			file.WriteString("\t" + imp + "\n")
		}

		if len(std) > 0 && len(other) > 0 {
			file.WriteString("\n")
		}

		for _, imp := range other {
			file.WriteString("\t" + imp + "\n")
		}

		file.WriteString(")\n\n")
	}

	file.WriteString(src)

	formatted, err := format.Source(file.Bytes())
	if err != nil {
		return nil, errors.NewProcessingError("gofmt of generated %s failed; source:\n%s", t.File, file.String(), err)
	}

	return formatted, nil
}

func isContext(t types.Type) bool {
	n, ok := t.(*types.Named)
	return ok && n.Obj().Pkg() != nil && n.Obj().Pkg().Path() == "context" && n.Obj().Name() == "Context"
}

func isError(t types.Type) bool {
	return types.Identical(t, types.Universe.Lookup("error").Type())
}

// renderMethod writes one delegating method and reports whether it returns an error.
func renderMethod(w *bytes.Buffer, im *importer, t Target, name string, sig *types.Signature) bool {
	params := sig.Params()
	results := sig.Results()

	var (
		decl     []string // parameter declarations
		callArgs []string // arguments to the wrapped call
		logArgs  []string // arguments recorded in the log
		ctxArg   = "nil"
	)

	for i := 0; i < params.Len(); i++ {
		pn := fmt.Sprintf("p%d", i)
		pt := params.At(i).Type()

		if sig.Variadic() && i == params.Len()-1 {
			decl = append(decl, pn+" ..."+im.typeString(pt.(*types.Slice).Elem()))
			callArgs = append(callArgs, pn+"...")
		} else {
			decl = append(decl, pn+" "+im.typeString(pt))
			callArgs = append(callArgs, pn)
		}

		if i == 0 && isContext(pt) {
			ctxArg = pn
			continue
		}

		logArgs = append(logArgs, pn)
	}

	hasErr := results.Len() > 0 && isError(results.At(results.Len()-1).Type())

	var resDecl, resNames []string

	for i := 0; i < results.Len(); i++ {
		rn := fmt.Sprintf("r%d", i)
		resNames = append(resNames, rn)
		resDecl = append(resDecl, rn+" "+im.typeString(results.At(i).Type()))
	}

	resSig := ""
	if len(resDecl) > 0 {
		resSig = " (" + strings.Join(resDecl, ", ") + ")"
	}

	enterArgs := append([]string{ctxArg, t.StoreKey, fmt.Sprintf("%q", name), fmt.Sprintf("%t", hasErr)}, logArgs...)

	fmt.Fprintf(w, "func (w *%s) %s(%s)%s {\n", t.Type, name, strings.Join(decl, ", "), resSig)
	fmt.Fprintf(w, "\tc := w.plan.enter(%s)\n", strings.Join(enterArgs, ", "))

	call := fmt.Sprintf("w.inner.%s(%s)", name, strings.Join(callArgs, ", "))

	switch {
	case hasErr:
		last := resNames[len(resNames)-1]
		fmt.Fprintf(w, "\tif err := c.before(); err != nil {\n\t\t%s = c.after(err)\n\t\treturn %s\n\t}\n\n", last, strings.Join(resNames, ", "))
		fmt.Fprintf(w, "\t%s = %s\n", strings.Join(resNames, ", "), call)
		fmt.Fprintf(w, "\t%s = c.after(%s)\n\n\treturn %s\n", last, last, strings.Join(resNames, ", "))
	case len(resNames) > 0:
		fmt.Fprintf(w, "\t_ = c.before()\n\n")
		fmt.Fprintf(w, "\t%s = %s\n", strings.Join(resNames, ", "), call)
		fmt.Fprintf(w, "\tc.after(nil)\n\n\treturn %s\n", strings.Join(resNames, ", "))
	default:
		fmt.Fprintf(w, "\t_ = c.before()\n\n")
		fmt.Fprintf(w, "\t%s\n", call)
		fmt.Fprintf(w, "\tc.after(nil)\n")
	}

	fmt.Fprintf(w, "}\n\n")

	return hasErr
}

func renderRegistry(registry map[string]map[string]bool) ([]byte, error) {
	methods := make([]string, 0, len(registry))
	for m := range registry {
		methods = append(methods, m)
	}

	sort.Strings(methods)

	var b bytes.Buffer

	b.WriteString(header)
	b.WriteString("package fault\n\n")
	b.WriteString("// methodErrors maps each decorated method name to the interfaces that declare it, and whether\n")
	b.WriteString("// it returns an error there.\n")
	b.WriteString("var methodErrors = map[string]map[string]bool{\n")

	for _, m := range methods {
		stores := make([]string, 0, len(registry[m]))
		for s := range registry[m] {
			stores = append(stores, s)
		}

		sort.Strings(stores)

		parts := make([]string, 0, len(stores))
		for _, s := range stores {
			parts = append(parts, fmt.Sprintf("%s: %t", s, registry[m][s]))
		}

		fmt.Fprintf(&b, "\t%q: {%s},\n", m, strings.Join(parts, ", "))
	}

	b.WriteString("}\n")

	return format.Source(b.Bytes())
}
